-- Миграция: Упрощение статусов задач
-- Было: Сделать, В работе, Проверка, Правки, Закрыто, Отменено
-- Стало: В работе, Доработки, Готово
-- ============================================================

-- Удаляем старые статусы
DELETE FROM `task_statuses`;

-- Вставляем новые
INSERT INTO `task_statuses` (`id`, `code`, `name`, `sort_order`) VALUES
(1, 'in_progress', 'В работе', 1),
(2, 'revision', 'Доработки', 2),
(3, 'done', 'Готово', 3);

-- Обновляем задачи с удалёнными статусами на "В работе" (id=1)
UPDATE `tasks` SET `status_id` = 1 WHERE `status_id` NOT IN (1, 2, 3);
