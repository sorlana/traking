-- Добавляем статус «Закрыто» (задача проверена и принята руководителем)
-- Статус «Готово» (done) = исполнитель отправил на проверку
-- Статус «Закрыто» (closed) = руководитель подтвердил принятие
INSERT INTO `task_statuses` (`code`, `name`, `sort_order`) VALUES ('closed', 'Закрыто', 4)
ON DUPLICATE KEY UPDATE `name` = 'Закрыто';

-- Обновляем название, если статус уже существует со старым названием «Сделано»
UPDATE `task_statuses` SET `name` = 'Закрыто' WHERE `code` = 'closed';
